/**
 * restaurant-data.ts
 *
 * THE single source of truth for all restaurant content.
 * - `RestaurantData` is the canonical type for every field.
 * - `defaultRestaurantData` is the seed — the live site is pixel-identical
 *   when this is unmodified.
 * - At runtime, the CMS reads from data/restaurant.json (if it exists) and deep-merges
 *   with these defaults so new fields are always forward-compatible.
 *
 * OPERATOR NOTE: To reset a deployed site to defaults, delete data/restaurant.json.
 */

// ─── Types ────────────────────────────────────────────────────────────────────

export type MenuItem = {
  name: string;
  desc?: string;
  price: string;
  veg?: boolean;
  star?: boolean;
};

export type MenuCategory = {
  id: string;
  label: string;
  items: MenuItem[];
};

export type SignatureDish = {
  name: string;
  tag: string;
  price: string;
  img: string;
  veg: boolean;
};

export type Review = {
  text: string;
  who: string;
};

export type GalleryPhoto = {
  src: string;
  cat: "ambience" | "food" | "drinks" | "food_drinks" | "party";
  caption: string;
};

export type Milestone = {
  year: string;
  title: string;
  body: string;
};

export type Stat = {
  n: string;
  l: string;
};

export type SeoPageMeta = {
  title: string;
  description: string;
  ogImage?: string;
};

export type RestaurantData = {
  // ── Identity ──────────────────────────────────────────────────────────────
  name: string;
  tagline: string;
  logoUrl: string;
  loadingSubtext?: string;   // e.g. "warming up the grill..."
  foundedYear: string;

  // ── Contact ───────────────────────────────────────────────────────────────
  address: string;           // Full address for contact page
  addressShort: string;      // Abbreviated for footer
  phone: string;             // Display format e.g. "+91 99997 39766"
  whatsappNumber: string;    // Digits only e.g. "919999739766" for wa.me links
  hours: string;             // e.g. "10:00 am – 10:30 pm every day"
  hoursShort: string;        // e.g. "Open daily · 10 AM – 10:30 PM"
  priceRange: string;        // e.g. "Approx ₹400–900 for two · cards & UPI accepted"

  // ── Social / Maps ─────────────────────────────────────────────────────────
  socialLinks: {
    instagram: string;
    maps: string;
  };
  mapsEmbedQuery: string;    // Query string for Google Maps embed src

  // ── Hero (homepage) ───────────────────────────────────────────────────────
  heroLocationBadge: string; // e.g. "Satya Niketan · open till 10:30 PM"
  heroHeadline: [string, string, string]; // 3 lines; line[1] gets coral colour, line[2] gets marker-underline
  heroHeadlineSince: string; // The "since YEAR" script annotation on h1
  heroSubcopy: string;
  heroStats: string[];       // Small stat pills below CTA buttons
  heroStats: string[];       // Small stat pills below CTA buttons
  heroCollagePhotos: [string, string]; // 2 collage photo URLs
  heroCollageAlts: [string, string];
  heroCollageAnnotation: string; // Handwritten annotation on the collage

  // ── Marquee ───────────────────────────────────────────────────────────────
  marqueeItems: string[];
  marqueeDishes?: string[];  // 5 custom dish names displayed on the moving bar

  // ── Story teaser (homepage section) ───────────────────────────────────────
  storyTeaserPhoto: string;
  storyTeaserPhotoAlt: string;
  storyTeaserScriptLabel: string;
  storyTeaserPrefix?: string;      // e.g. "Eleven years of"
  storyTeaserH2: [string, string]; // [normal part, coral/highlighted part]
  storyTeaserBody: string;

  // ── About page ────────────────────────────────────────────────────────────
  milestones: Milestone[];
  stats: Stat[];
  pressQuote: string;
  pressAttribution: string;

  // ── Menu ──────────────────────────────────────────────────────────────────
  menu: MenuCategory[];

  // ── Signature dishes (homepage) ───────────────────────────────────────────
  signatureDishes: SignatureDish[];

  // ── Reviews ───────────────────────────────────────────────────────────────
  reviews: Review[];

  // ── Gallery ───────────────────────────────────────────────────────────────
  galleryPhotos: GalleryPhoto[];
  homepageGalleryPhotos?: string[]; // 10 featured showcase photos for homepage & gallery "Everything"

  // ── Footer ────────────────────────────────────────────────────────────────
  footerTagline: string;   // e.g. "since 2014"
  footerBody: string;      // Paragraph under the name/tagline

  // ── SEO meta per page ─────────────────────────────────────────────────────
  seoMeta: {
    home: SeoPageMeta;
    menu: SeoPageMeta;
    about: SeoPageMeta;
    contact: SeoPageMeta;
    gallery: SeoPageMeta;
  };

  // ── CMS lock ──────────────────────────────────────────────────────────────
  isLocked: boolean;
  autoGeneratedFields?: string[];
};

