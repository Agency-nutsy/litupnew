/**
 * Normalizes any Google Maps input (full embed URL, <iframe> snippet, place search query, or maps link)
 * into a valid, safe iframe src URL.
 */
export function getGoogleMapsEmbedUrl(queryOrUrl?: string): string {
  if (!queryOrUrl || !queryOrUrl.trim()) {
    return "https://www.google.com/maps?q=The+Litup+Cafe+Hudson+Lane&output=embed";
  }
  const trimmed = queryOrUrl.trim();

  // If a full <iframe> snippet was pasted (e.g. from Google Maps "Embed a map")
  const iframeMatch = trimmed.match(/src=["']([^"']+)["']/i);
  if (iframeMatch && iframeMatch[1]) {
    return iframeMatch[1];
  }

  // If already a Google Maps embed URL
  if (trimmed.includes("google.com/maps/embed")) {
    return trimmed;
  }

  // If already an embed query
  if (trimmed.includes("output=embed")) {
    return trimmed;
  }

  // If it's a URL or search text, construct standard embed
  return `https://www.google.com/maps?q=${encodeURIComponent(trimmed)}&output=embed`;
}
